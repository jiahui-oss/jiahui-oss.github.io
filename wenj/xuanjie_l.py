def 存在存档():
    """是否存在存档"""
    return os.path.exists(存档路径)


def 保存存档(数据: dict):
    """写入存档"""
    存档内容 = {
        **数据,
        "保存时间": datetime.now().isoformat()
    }
    with open(存档路径, "w", encoding="utf-8") as 文件:
        json.dump(存档内容, 文件, ensure_ascii=False, indent=2)


def 读取存档():
    """读取存档，无则返回 None"""
    if not 存在存档():
        return None
    with open(存档路径, "r", encoding="utf-8") as 文件:
        return json.load(文件)
